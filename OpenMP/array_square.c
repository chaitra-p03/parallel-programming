#include <stdio.h>
#include <stdlib.h>
#include <omp.h>

#define SIZE 10

int main() {
    int arr[SIZE];

    #pragma omp parallel
    {
        #pragma omp single
        {
            printf("Array generated by Thread %d\n", omp_get_thread_num());
            for (int i = 0; i < SIZE; i++) {
                arr[i] = rand() % 10;
            }
        }
        #pragma omp for
        for (int i = 0; i < SIZE; i++) {
            int tid = omp_get_thread_num();
            int prev = arr[i];
            arr[i] = arr[i] * arr[i];
            printf("Thread %d processed element %d at %d, square = %d\n", tid, prev, i, arr[i]);
        }
    }

    return 0;
}